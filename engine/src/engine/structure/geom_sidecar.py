"""S2.1.3 — the persisted geometry sidecar (``s2_1_plan.md`` DT-9; issue #37).

Geometry is L1 fact, but the frozen atom streams are what the user is actively authoring
against — S2.1 does **not** re-emit them. The matcher's output lands in a versioned **sidecar**
``books/<id>/work/data/geometry/{witness}_geom.json`` (gitignored ``work/data/``, disposable by
convention: the tracked verdict file + inputs regenerate it deterministically, DT-10). This module
owns the record vocabulary, the model invariants, the load/save boundary, and the P-5 auto-absent
tripwire; the matcher that *produces* the records is ``geom_match`` (which imports from here —
one-directional, never the reverse).

The model enforces the state split the plan pins (DT-8/DT-9):

- **Page records** — ``status ∈ {matched, routed, declined}``. A ``routed`` page's atoms are
  simply **absent from** ``atoms`` (*pending* ≠ ``Geom.absent`` — G-12); a ``declined`` page
  carries the human verdict on its page record (#40 writes it). Construction rejects an atom
  record whose assigned page is not ``matched`` — the absent-write-before-verdict fault is
  *unconstructible*, not merely untested.
- **Atom records** — ``status ∈ {matched, unmatched}``; the persisted unmatched ``reason`` enum is
  **closed** at three values (``zero_match`` / ``below_atom_floor`` / ``ambiguous``, R19). The
  attach-time outcomes (``ineligible``/``multi_primary_derivation``) are deliberately *not*
  admissible here — they are derived at ``attach_geometry`` from ``derived_from`` and can never be
  persisted as match failures (G-25).
- **``atom_pages``** — every stream atom's *derived* page window plus its assigned page: the DT-3
  byproduct (real page attribution for a ``PAGE_UNMAPPED`` witness, as derived sidecar data —
  never a frozen-stream mutation) and the map that lets ``attach_geometry`` tell a *pending* atom
  (assigned page routed) from a *declined* one without per-atom pending records.

Binding (R11): ``stream_source_hash`` pins the witness stream this sidecar matched
(``AtomStream.source_hash``); ``source_scan`` + ``backend_params``/``engine_id`` pin the scan and
the OCR pass the boxes came from. :func:`save_geom_sidecar` refuses to regenerate over an existing
sidecar whose scan identity disagrees, and :func:`assert_source_scan_matches` is the replay-side
check (G-19) — both the D14/D21 stale posture, so drift is loud, never silently absorbed.

Load boundary: the shared taxonomy (G-18) — an absent file is
:class:`~engine.errors.MissingInputError`; a present-but-unloadable/stale/malformed one is
:class:`~engine.errors.StaleArtifactError`; nothing else escapes the loader. The tripwire raises
:class:`~engine.structure.geometry.GeometryError` — an integrity gate, not a load fault.

Pure core: no language, book, or witness-name opinion lives here — witness ids, reasons for a
book's layout, and every threshold's *inputs* are caller-supplied (the S0.2 neutrality guard scans
this module). The P-5 tripwire constants are ruled algorithm parameters, value-pin tested.
"""

