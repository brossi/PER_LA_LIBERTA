@dataclass(frozen=True, slots=True)
class SourceScan:
    """The scan-identity fingerprint (R11): ``kind`` is the discriminator (``"pdf"`` today; a
    future image-bundle backend adds its own kind without a rename or version bump), ``sha256``
    the content hash, ``n_pages`` the page count, ``n_bytes`` the size (persisted as ``bytes``).
    All join the DT-10 input fingerprint; :func:`assert_source_scan_matches` is the replay check."""

    kind: str
    sha256: str
    n_pages: int
    n_bytes: int

    def __post_init__(self) -> None:
        if not (isinstance(self.kind, str) and self.kind.strip()):
            raise ValueError(f"source_scan.kind must be a non-empty discriminator, got {self.kind!r}")
        if not (isinstance(self.sha256, str) and self.sha256.strip()):
            raise ValueError("source_scan.sha256 must be a non-empty content hash")
        if not (_is_int(self.n_pages) and self.n_pages > 0):
            raise ValueError(f"source_scan.n_pages must be a positive integer, got {self.n_pages!r}")
        if not (_is_int(self.n_bytes) and self.n_bytes > 0):
            raise ValueError(f"source_scan.bytes must be a positive integer, got {self.n_bytes!r}")


@dataclass(frozen=True, slots=True)
class PageRecord:
    """One page's sidecar state (DT-9). The shape is status-conditional and enforced:

    - ``matched`` — ``match_rate`` required (the accepted page's atom-weighted rate); routing
      fields and ``verdict`` forbidden.
    - ``routed`` — ``stage``/``signal``/``value`` required (which gate fired and at what value);
      ``match_rate``/``verdict`` forbidden. The page's atoms are *pending*: absent from the atoms
      map, never written absent (G-12).
    - ``declined`` — ``verdict`` required (the human record, #40 writes it); everything else
      forbidden.

    ``dropped_boxes`` (the backend's DT-2 per-page normalization count) is a backend stat valid on
    any status; ``None`` means the producer had no count, which is distinct from ``0``.

    The detector fields (``n_cols``/``n_cols_source``/``order_qa`` — DT-9/DT-12, schema v2) are the
    segmentation front-end's per-page output on an **accepted** page: the resolved column count, its
    origin (own ``evidence`` or the cross-page ``prior``), and ``order_qa`` — the ordered coverage of
    the detector-ordered boxes against the witness window (the S2.2 measurement feed). They are
    forbidden on a routed/declined page (no accepted geometry to measure), and ``n_cols`` /
    ``n_cols_source`` are set together (a count has an origin, or both are absent — e.g. a
    matcher-built record before the detector wiring runs).
    """

    status: str
    match_rate: float | None = None
    dropped_boxes: int | None = None
    stage: str | None = None
    signal: str | None = None
    value: float | None = None
    verdict: Mapping | None = None
    n_cols: int | None = None
    n_cols_source: str | None = None
    order_qa: float | None = None

    def __post_init__(self) -> None:
        if self.status not in PAGE_STATUSES:
            raise ValueError(f"page status must be one of {PAGE_STATUSES}, got {self.status!r}")
        if self.dropped_boxes is not None and not (_is_int(self.dropped_boxes) and self.dropped_boxes >= 0):
            raise ValueError(f"dropped_boxes must be a non-negative integer or None, got {self.dropped_boxes!r}")
        self._check_detector_fields()
        if self.status == PAGE_MATCHED:
            if not _is_rate(self.match_rate):
                raise ValueError(f"a matched page requires match_rate in [0, 1], got {self.match_rate!r}")
            if self.stage is not None or self.signal is not None or self.value is not None or self.verdict is not None:
                raise ValueError("a matched page carries no routing fields or verdict")
        elif self.status == PAGE_ROUTED:
            if not (isinstance(self.stage, str) and self.stage.strip()):
                raise ValueError("a routed page requires the stage that routed it")
            if not (isinstance(self.signal, str) and self.signal.strip()):
                raise ValueError("a routed page requires the signal that routed it")
            if not (
                isinstance(self.value, (int, float))
                and not isinstance(self.value, bool)
                and math.isfinite(self.value)
            ):
                raise ValueError(f"a routed page requires the finite signal value, got {self.value!r}")
            if self.match_rate is not None or self.verdict is not None:
                raise ValueError("a routed page carries no match_rate or verdict (its atoms are pending)")
        else:  # declined
            if not (isinstance(self.verdict, Mapping) and self.verdict):
                raise ValueError("a declined page requires the non-empty human verdict record")
            if self.match_rate is not None or self.stage is not None or self.signal is not None or self.value is not None:
                raise ValueError("a declined page carries only its verdict")
            object.__setattr__(self, "verdict", dict(self.verdict))

    def _check_detector_fields(self) -> None:
        """The schema-v2 detector fields (DT-12): valid domains, coherent count↔source, and
        matched-only (a routed/declined page has no accepted geometry to measure)."""
        if self.n_cols is not None and not (_is_int(self.n_cols) and self.n_cols in (1, 2)):
            raise ValueError(f"n_cols must be 1, 2, or None, got {self.n_cols!r}")
        if self.n_cols_source is not None and self.n_cols_source not in N_COLS_SOURCES:
            raise ValueError(f"n_cols_source must be one of {N_COLS_SOURCES} or None, got {self.n_cols_source!r}")
        if (self.n_cols is None) != (self.n_cols_source is None):
            raise ValueError(
                "n_cols and n_cols_source are set together (a column count has a source, or both are absent), "
                f"got n_cols={self.n_cols!r} n_cols_source={self.n_cols_source!r}"
            )
        if self.order_qa is not None and not _is_rate(self.order_qa):
            raise ValueError(f"order_qa must be a rate in [0, 1] or None, got {self.order_qa!r}")
        if self.status != PAGE_MATCHED and (
            self.n_cols is not None or self.n_cols_source is not None or self.order_qa is not None
        ):
            raise ValueError(
                "only a matched page carries detector fields (n_cols/n_cols_source/order_qa) — a "
                f"{self.status!r} page has no accepted geometry to measure"
            )


@dataclass(frozen=True, slots=True)
class AtomRecord:
    """One accepted-page atom's match state (DT-8/DT-9). ``matched`` carries ``page`` + ``bbox``
    (the union over matched boxes only) + ``match_method``; ``unmatched`` carries a ``reason`` from
    the closed :data:`UNMATCHED_REASONS` enum and **no bbox** — absent, never a plausible wrong
    box. Both carry the measured ``match_confidence``."""

    status: str
    match_confidence: float
    page: int | None = None
    bbox: tuple[float, float, float, float] | None = None
    match_method: str | None = None
    reason: str | None = None

    def __post_init__(self) -> None:
        if self.status not in ATOM_STATUSES:
            raise ValueError(f"atom status must be one of {ATOM_STATUSES}, got {self.status!r}")
        if not _is_rate(self.match_confidence):
            raise ValueError(f"match_confidence must be in [0, 1], got {self.match_confidence!r}")
        if self.status == ATOM_MATCHED:
            if not (_is_int(self.page) and self.page > 0):
                raise ValueError(f"a matched atom requires its positive scan page, got {self.page!r}")
            if not isinstance(self.bbox, (tuple, list)) or len(self.bbox) != 4:
                raise ValueError(f"a matched atom requires a four-float bbox, got {self.bbox!r}")
            object.__setattr__(self, "bbox", tuple(float(c) for c in self.bbox))
            if not all(math.isfinite(c) for c in self.bbox):
                raise ValueError(f"bbox coordinates must be finite, got {self.bbox!r}")
            x0, y0, x1, y1 = self.bbox
            if x1 <= x0 or y1 <= y0:
                raise ValueError(f"bbox must be non-degenerate (x1 > x0 and y1 > y0), got {self.bbox!r}")
            if not (isinstance(self.match_method, str) and self.match_method.strip()):
                raise ValueError("a matched atom requires its match_method")
            if self.reason is not None:
                raise ValueError("a matched atom carries no unmatched reason")
        else:
            if self.reason not in UNMATCHED_REASONS:
                # The closed enum is load-bearing (R19/G-25): an attach-time outcome (ineligible /
                # multi-derivation) persisted here would silently become a match failure.
                raise ValueError(
                    f"an unmatched atom's reason must be one of {UNMATCHED_REASONS}, got {self.reason!r}"
                )
            if self.page is not None or self.bbox is not None or self.match_method is not None:
                raise ValueError("an unmatched atom carries no page/bbox/match_method — absent, never invented")


@dataclass(frozen=True, slots=True)
class AtomPages:
    """One stream atom's *derived* page attribution (the DT-3 byproduct): the window of scan pages
    its tokens overlap (``first``..``last``) and the single ``assigned`` page whose bag it matched
    against — the page whose record governs its state at ``attach_geometry``."""

    first: int
    last: int
    assigned: int

    def __post_init__(self) -> None:
        for name, value in (("first", self.first), ("last", self.last), ("assigned", self.assigned)):
            if not (_is_int(value) and value > 0):
                raise ValueError(f"atom_pages.{name} must be a positive scan page, got {value!r}")
        if not (self.first <= self.assigned <= self.last):
            raise ValueError(
                f"atom_pages must satisfy first <= assigned <= last, got "
                f"({self.first}, {self.assigned}, {self.last})"
            )


@dataclass(frozen=True, slots=True)
class GeomSidecar:
    """The whole persisted sidecar (DT-9), model-validated at construction.

    Cross-record invariants enforced here (so the faults are unconstructible, not merely
    untested): every atom record's atom must appear in ``atom_pages``; every ``atom_pages`` page
    must have a page record; an atom record's **assigned page must be ``matched``** — a routed or
    declined page's atoms are pending/declined by *absence* from the atoms map (G-12), and
    auto-absent records exist only on accepted pages (DT-8's scope split); a matched atom record's
    ``page`` must equal its assigned page.
    """

    witness_id: str
    stream_source_hash: str
    source_scan: SourceScan
    backend_params: Mapping[str, object]
    engine_id: str
    locate_method: str
    pages: Mapping[int, PageRecord]
    atoms: Mapping[str, AtomRecord]
    atom_pages: Mapping[str, AtomPages]
    coverage: Mapping[str, int | None]  # None only on the two canonical counters: "unmeasured"
    classifier_version: str | None = None
    classifier_params: Mapping[str, object] | None = None
    schema_version: int = GEOM_SIDECAR_SCHEMA_VERSION

    def __post_init__(self) -> None:
        _check_witness_id(self.witness_id)
        if not (isinstance(self.stream_source_hash, str) and self.stream_source_hash.strip()):
            raise ValueError("stream_source_hash must be the witness stream's non-empty source_hash anchor")
        if not isinstance(self.source_scan, SourceScan):
            raise ValueError(f"source_scan must be a SourceScan record, got {type(self.source_scan).__name__}")
        if not (isinstance(self.backend_params, Mapping) and self.backend_params):
            raise ValueError("backend_params must be the backend's non-empty structured contract (DT-9)")
        if not (isinstance(self.engine_id, str) and self.engine_id.strip()):
            raise ValueError("engine_id must be the backend's non-empty reproducibility string")
        if not (isinstance(self.locate_method, str) and self.locate_method.strip()):
            raise ValueError("locate_method must name the page-locate algorithm")
        object.__setattr__(self, "backend_params", dict(self.backend_params))
        object.__setattr__(self, "pages", dict(self.pages))
        object.__setattr__(self, "atoms", dict(self.atoms))
        object.__setattr__(self, "atom_pages", dict(self.atom_pages))
        object.__setattr__(self, "coverage", dict(self.coverage))
        if self.classifier_params is not None:
            object.__setattr__(self, "classifier_params", dict(self.classifier_params))
        if self.classifier_version is not None and not (
            isinstance(self.classifier_version, str) and self.classifier_version.strip()
        ):
            raise ValueError(f"classifier_version must be a non-empty string or None, got {self.classifier_version!r}")

        for page, record in self.pages.items():
            if not (_is_int(page) and page > 0):
                raise ValueError(f"pages must be keyed by positive scan page integers, got {page!r}")
            if not isinstance(record, PageRecord):
                raise ValueError(f"pages[{page}] must be a PageRecord, got {type(record).__name__}")
        for atom_id, window in self.atom_pages.items():
            if not (isinstance(atom_id, str) and atom_id):
                raise ValueError(f"atom_pages must be keyed by atom ids, got {atom_id!r}")
            if not isinstance(window, AtomPages):
                raise ValueError(f"atom_pages[{atom_id!r}] must be an AtomPages record")
            for page in range(window.first, window.last + 1):
                if page not in self.pages:
                    raise ValueError(
                        f"atom_pages[{atom_id!r}] window covers page {page}, which has no page record"
                    )
        for atom_id, record in self.atoms.items():
            if not (isinstance(atom_id, str) and atom_id):
                raise ValueError(f"atoms must be keyed by atom ids, got {atom_id!r}")
            if not isinstance(record, AtomRecord):
                raise ValueError(f"atoms[{atom_id!r}] must be an AtomRecord")
            if atom_id not in self.atom_pages:
                raise ValueError(f"atoms[{atom_id!r}] has no atom_pages window — records exist only for located atoms")
            assigned = self.atom_pages[atom_id].assigned
            if self.pages[assigned].status != PAGE_MATCHED:
                # G-12 + DT-8's scope split, structurally: a routed page's atoms stay pending
                # (absent from this map) and auto-absents exist only on accepted pages, so an atom
                # record on a non-matched page is an absent-write before verdict.
                raise ValueError(
                    f"atoms[{atom_id!r}] sits on page {assigned} with status "
                    f"{self.pages[assigned].status!r} — atom records exist only on matched pages "
                    f"(a routed page's atoms stay pending, never written; G-12)"
                )
            if record.status == ATOM_MATCHED and record.page != assigned:
                raise ValueError(
                    f"atoms[{atom_id!r}] is matched on page {record.page} but assigned to page "
                    f"{assigned} — the record and the derived attribution disagree"
                )
        if set(self.coverage) != set(COVERAGE_KEYS):
            raise ValueError(
                f"coverage must carry exactly {COVERAGE_KEYS}, got {sorted(self.coverage)}"
            )
        for key in COVERAGE_KEYS:
            value = self.coverage[key]
            if value is None and key in _NULLABLE_COVERAGE_KEYS:
                continue  # unmeasured (no canonical stream at build) — distinct from a measured 0
            if not (_is_int(value) and value >= 0):
                raise ValueError(f"coverage[{key!r}] must be a non-negative integer, got {value!r}")


# --- serialization (envelope ⇄ GeomSidecar) ----------------------------------------------------- #


def _canonical_json(value):
    """Recursively key-sort every nested mapping (lists keep their order — order is data there),
    so serialization is a pure function of *content* all the way down — including a declined
    page's ``verdict`` payload and nested ``backend_params``/``classifier_params`` values, the
    byte-stability #40's idempotent replay asserts against."""
    if isinstance(value, Mapping):
        return {k: _canonical_json(value[k]) for k in sorted(value)}
    if isinstance(value, (list, tuple)):
        return [_canonical_json(v) for v in value]
    return value


def _reject_unknown_keys(data: Mapping, allowed: frozenset[str], ctx: str) -> None:
    """A document carrying keys this schema version does not define is a wrong-era or corrupt
    file; loading it with silent field loss would be a non-fail-loud branch in the loader.
    Applied at every mapping level the schema defines (envelope, source_scan, and each record)."""
    unknown = sorted(set(data) - allowed)
    if unknown:
        raise StaleArtifactError(f"malformed geometry sidecar {ctx}: unknown key(s) {unknown}")


