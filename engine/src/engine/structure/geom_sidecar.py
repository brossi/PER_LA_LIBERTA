_ATOM_RECORD_KEYS = frozenset({"status", "match_confidence", "page", "bbox", "match_method", "reason"})
_ATOM_PAGES_KEYS = frozenset({"pages", "assigned"})


def _page_record_to_json(record: PageRecord) -> dict:
    out: dict = {"status": record.status}
    for key in ("match_rate", "dropped_boxes", "stage", "signal", "value", "n_cols", "n_cols_source", "order_qa"):
        value = getattr(record, key)
        if value is not None:
            out[key] = value
    if record.verdict is not None:
        out["verdict"] = _canonical_json(record.verdict)
    return out


def _page_record_from_json(data: Mapping) -> PageRecord:
    if not isinstance(data, Mapping):
        raise StaleArtifactError(f"page record must be a JSON object, got {type(data).__name__}")
    _reject_unknown_keys(data, _PAGE_RECORD_KEYS, "page record")
    return PageRecord(
        status=_require(data, "status", "page record"),
        match_rate=data.get("match_rate"),
        dropped_boxes=data.get("dropped_boxes"),
        stage=data.get("stage"),
        signal=data.get("signal"),
        value=data.get("value"),
        verdict=data.get("verdict"),
        n_cols=data.get("n_cols"),
        n_cols_source=data.get("n_cols_source"),
        order_qa=data.get("order_qa"),
    )


def _atom_record_to_json(record: AtomRecord) -> dict:
    out: dict = {"status": record.status, "match_confidence": record.match_confidence}
    if record.status == ATOM_MATCHED:
        out["page"] = record.page
        out["bbox"] = list(record.bbox)
        out["match_method"] = record.match_method
    else:
        out["reason"] = record.reason
    return out


def _atom_record_from_json(data: Mapping) -> AtomRecord:
    if not isinstance(data, Mapping):
        raise StaleArtifactError(f"atom record must be a JSON object, got {type(data).__name__}")
    _reject_unknown_keys(data, _ATOM_RECORD_KEYS, "atom record")
    bbox = data.get("bbox")
    return AtomRecord(
        status=_require(data, "status", "atom record"),
        match_confidence=_require(data, "match_confidence", "atom record"),
        page=data.get("page"),
        bbox=tuple(bbox) if bbox is not None else None,
        match_method=data.get("match_method"),
        reason=data.get("reason"),
    )


def _atom_pages_to_json(window: AtomPages) -> dict:
    return {"pages": [window.first, window.last], "assigned": window.assigned}


def _atom_pages_from_json(data: Mapping) -> AtomPages:
    if not isinstance(data, Mapping):
        raise StaleArtifactError(f"atom_pages record must be a JSON object, got {type(data).__name__}")
    _reject_unknown_keys(data, _ATOM_PAGES_KEYS, "atom_pages record")
    pages = _require(data, "pages", "atom_pages record")
    if not isinstance(pages, (list, tuple)) or len(pages) != 2:
        raise StaleArtifactError(f"atom_pages.pages must be [first, last], got {pages!r}")
    return AtomPages(first=pages[0], last=pages[1], assigned=_require(data, "assigned", "atom_pages record"))


def to_json(sidecar: GeomSidecar) -> dict:
    """The persisted envelope for ``sidecar``, a pure function of the sidecar's *content*: the
    fixed-schema levels (envelope, ``coverage``) emit in schema order, and every *dynamic* mapping
    is key-sorted (pages numerically, atoms lexicographically, nested payloads recursively via
    ``_canonical_json``) — the byte-stability the G-24 determinism red and #40's idempotent
    replay both assert against."""
    envelope: dict = {
        "schema_version": sidecar.schema_version,
        "stale_class": GEOM_SIDECAR_STALE_CLASS,
        "witness_id": sidecar.witness_id,
        "stream_source_hash": sidecar.stream_source_hash,
        "source_scan": {
            "kind": sidecar.source_scan.kind,
            "sha256": sidecar.source_scan.sha256,
            "n_pages": sidecar.source_scan.n_pages,
            "bytes": sidecar.source_scan.n_bytes,
        },
        "backend_params": _canonical_json(sidecar.backend_params),
        "engine_id": sidecar.engine_id,
        "locate_method": sidecar.locate_method,
        "classifier_version": sidecar.classifier_version,
        "classifier_params": (
            _canonical_json(sidecar.classifier_params)
            if sidecar.classifier_params is not None
            else None
        ),
        "pages": {str(p): _page_record_to_json(sidecar.pages[p]) for p in sorted(sidecar.pages)},
        "atoms": {a: _atom_record_to_json(sidecar.atoms[a]) for a in sorted(sidecar.atoms)},
        "atom_pages": {a: _atom_pages_to_json(sidecar.atom_pages[a]) for a in sorted(sidecar.atom_pages)},
        "coverage": {k: sidecar.coverage[k] for k in COVERAGE_KEYS},
    }
    return envelope


def from_json(data: Mapping) -> GeomSidecar:
    """Parse + validate a persisted envelope, or fail loud (the total load-boundary contract):
    a valid :class:`GeomSidecar` or :class:`~engine.errors.StaleArtifactError`, never a bare
    traceback (G-18)."""
    if not isinstance(data, Mapping):
        raise StaleArtifactError(
            f"geometry-sidecar envelope must be a JSON object, got {type(data).__name__}"
        )
    version = _require(data, "schema_version", "envelope")
    if version != GEOM_SIDECAR_SCHEMA_VERSION:
        raise StaleArtifactError(
            f"geometry-sidecar schema version {version!r} != current {GEOM_SIDECAR_SCHEMA_VERSION!r} "
            f"(stale class {GEOM_SIDECAR_STALE_CLASS!r}) — regenerate the sidecar"
        )
    stale_class = _require(data, "stale_class", "envelope")
    if stale_class != GEOM_SIDECAR_STALE_CLASS:
        raise StaleArtifactError(
            f"stale_class {stale_class!r} != {GEOM_SIDECAR_STALE_CLASS!r} — not a geometry sidecar "
            f"(a different persisted layer, or a malformed file)"
        )
    _reject_unknown_keys(data, _ENVELOPE_KEYS, "envelope")
    try:
        scan = _require(data, "source_scan", "envelope")
        if not isinstance(scan, Mapping):
            raise StaleArtifactError(f"source_scan must be a JSON object, got {type(scan).__name__}")
        _reject_unknown_keys(scan, _SOURCE_SCAN_KEYS, "source_scan")
        source_scan = SourceScan(
            kind=_require(scan, "kind", "source_scan"),
            sha256=_require(scan, "sha256", "source_scan"),
            n_pages=_require(scan, "n_pages", "source_scan"),
            n_bytes=_require(scan, "bytes", "source_scan"),
        )
        raw_pages = _require(data, "pages", "envelope")
        if not isinstance(raw_pages, Mapping):
            raise StaleArtifactError(f"pages must be a JSON object, got {type(raw_pages).__name__}")
        pages: dict[int, PageRecord] = {}
        for key, record in raw_pages.items():
            if not (isinstance(key, str) and key.isdigit()):
                raise StaleArtifactError(f"pages keys must be scan-page integers, got {key!r}")
            pages[int(key)] = _page_record_from_json(record)
        raw_atoms = _require(data, "atoms", "envelope")
        if not isinstance(raw_atoms, Mapping):
            raise StaleArtifactError(f"atoms must be a JSON object, got {type(raw_atoms).__name__}")
        raw_windows = _require(data, "atom_pages", "envelope")
        if not isinstance(raw_windows, Mapping):
            raise StaleArtifactError(f"atom_pages must be a JSON object, got {type(raw_windows).__name__}")
        return GeomSidecar(
            witness_id=_require(data, "witness_id", "envelope"),
            stream_source_hash=_require(data, "stream_source_hash", "envelope"),
            source_scan=source_scan,
            backend_params=_require(data, "backend_params", "envelope"),
            engine_id=_require(data, "engine_id", "envelope"),
            locate_method=_require(data, "locate_method", "envelope"),
            pages=pages,
            atoms={a: _atom_record_from_json(r) for a, r in raw_atoms.items()},
            atom_pages={a: _atom_pages_from_json(w) for a, w in raw_windows.items()},
            coverage=_require(data, "coverage", "envelope"),
            classifier_version=data.get("classifier_version"),
            classifier_params=data.get("classifier_params"),
            schema_version=version,
        )
    except StaleArtifactError:
        raise
    except (ValueError, TypeError) as exc:
        # A model-invariant violation (bad status, invented-geometry shape, G-12 scope fault) or a
        # wrong-typed field in a *persisted* sidecar is corrupt data, not an in-memory programming
        # error: surface it through the load-boundary contract.
        raise StaleArtifactError(f"malformed geometry sidecar: {exc}") from exc


