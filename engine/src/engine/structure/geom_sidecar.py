#: Independent schema version of the geometry sidecar (M3 posture: one artifact, one version).
#: v2 (S2.1.6 / #40, DT-12) adds the segmentation-front-end detector fields to a matched page record
#: (``n_cols`` / ``n_cols_source`` / ``order_qa`` — the S2.2 measurement feed); a v1 file no longer
#: loads, which is correct (the sidecar is disposable and regenerated by the run).
GEOM_SIDECAR_SCHEMA_VERSION = 2
#: The envelope discriminator, so a load can reject a file that is structurally JSON but a
#: different persisted layer (the atom store / structure map / evidence sidecar all carry their
#: own). The sidecar is *disposable* (not S8.1-governed), so this is a wrong-artifact guard, not a
#: migration route — which is why it lives here beside its raiser, not in ``artifacts.py``'s
#: governed-layer roster.
GEOM_SIDECAR_STALE_CLASS = "geometry-sidecar"

#: Workspace area/subdir the sidecar lives under (``<work>/data/geometry/``) — an existing ignored
#: work area (R7), so nothing is added to ``paths._AREAS`` and containment is already enforced.
GEOMETRY_AREA = "data"
GEOMETRY_SUBDIR = "geometry"

# --- record vocabulary (closed sets — DT-9) ---------------------------------------------------- #

PAGE_MATCHED = "matched"
PAGE_ROUTED = "routed"
PAGE_DECLINED = "declined"
PAGE_STATUSES = (PAGE_MATCHED, PAGE_ROUTED, PAGE_DECLINED)

ATOM_MATCHED = "matched"
ATOM_UNMATCHED = "unmatched"
ATOM_STATUSES = (ATOM_MATCHED, ATOM_UNMATCHED)

#: The origin of a matched page's column count (DT-7/DT-9, schema v2): the page's own confident
#: detector verdict, or the cross-page prior inherited from an agreeing content neighbour. Mirrors
#: :class:`~engine.structure.segmentation.PageColumnVerdict`'s ``n_cols_source`` domain; a page with
#: no column decision carries ``None`` for both count and source.
N_COLS_SOURCES = ("evidence", "prior")

REASON_ZERO_MATCH = "zero_match"
REASON_BELOW_ATOM_FLOOR = "below_atom_floor"
REASON_AMBIGUOUS = "ambiguous"
#: The persisted unmatched-reason enum, **closed** at these three (R19): the attach-time outcomes
#: (``no_primary_derivation`` / ``multi_primary_derivation``) are derived from ``derived_from`` at
#: ``attach_geometry`` and must never be persisted as per-atom match failures (G-25/G-20).
UNMATCHED_REASONS = (REASON_ZERO_MATCH, REASON_BELOW_ATOM_FLOOR, REASON_AMBIGUOUS)

#: The four coverage counters DT-9 pins — loss counted separately and by cause, so the untried
#: secondary-witness lane stays visible as DT-13 evidence rather than silent coverage loss (R3).
COVERAGE_KEYS = (
    "pages_locate_failed",
    "atoms_unmatched_on_accepted_pages",
    "canonical_no_primary_derivation",
    "canonical_multi_primary_derivation",
)
#: The two canonical counters may be ``None`` — *unmeasured* (no canonical stream was given at
#: build), deliberately distinct from a measured 0 so a witness-only sidecar cannot masquerade as
#: "canonical fully covered" (they are DT-13's evidence, R3).
_NULLABLE_COVERAGE_KEYS = frozenset(
    {"canonical_no_primary_derivation", "canonical_multi_primary_derivation"}
)

# --- P-5 auto-absent tripwire constants (the two-leg form + warn tier RULED 2026-07-03; all four
# --- values pinned by test_tripwire_constants_are_the_ruled_p5_values, G-26) -------------------- #

#: Leg A: auto-absent token mass / accepted-page token mass may not exceed this. Sized against the
#: measured honest ceiling (the entire ≤3-token furniture tail is 1.3% of token mass, §2), so leg A
#: cannot fire on it even at total wipeout — any firing implies real prose mass absent.
TRIPWIRE_ABSENT_MASS_MAX = 0.02
#: Leg B scope: an atom is "prose-sized" for the tripwire at this many witness tokens or more.
TRIPWIRE_PROSE_MIN_TOKENS = 4
#: Leg B: the auto-absent *rate* among prose-sized atoms on accepted pages may not exceed this
#: (systematic absence, never honest residue). Catches the wide-but-thin failure leg A
#: underweights; leg A catches the mass-concentrated one leg B underweights.
TRIPWIRE_PROSE_ABSENT_RATE_MAX = 0.05
#: Warn tier (non-blocking): a token band whose auto-absent mass exceeds this fraction of
#: accepted-page token mass is flagged informationally in the returned stats.
TRIPWIRE_WARN_BAND_MASS = 0.01

# Same flat-stem discipline as the atom store's stream ids: the witness id lands in a filename
# template, so a path-shaped id (``../evil``, ``a/b``) is rejected at the model and the path
# accessor both — not merely blocked from escaping the workspace by ``resolve``'s containment.
_WITNESS_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


def _check_witness_id(witness_id: str) -> None:
    if not isinstance(witness_id, str) or not _WITNESS_ID.fullmatch(witness_id):
        raise ValueError(
            f"witness_id must be a flat filename stem matching {_WITNESS_ID.pattern!r}, got "
            f"{witness_id!r} — the sidecar is one {{witness}}_geom.json file, never a nested path"
        )


def _require(data: Mapping, key: str, ctx: str):
    """Fetch ``data[key]`` or fail loud as a malformed envelope (the load-boundary contract)."""
    if key not in data:
        raise StaleArtifactError(f"malformed geometry sidecar {ctx}: missing required key {key!r}")
    return data[key]


def _is_int(value) -> bool:
    # Exact-type: bool is an int subclass and True is not a page number or a count.
    return type(value) is int


def _is_rate(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value) and 0.0 <= value <= 1.0


