def geom_sidecar_path(workspace: BookWorkspace, witness_id: str) -> Path:
    """The containment-checked path to ``<work>/data/geometry/{witness_id}_geom.json``."""
    _check_witness_id(witness_id)
    return workspace.resolve(GEOMETRY_AREA, GEOMETRY_SUBDIR, f"{witness_id}_geom.json")


def save_geom_sidecar(workspace: BookWorkspace, sidecar: GeomSidecar) -> Path:
    """Persist ``sidecar`` atomically; return the path.

    Generation guard (G-19, the regen-guard posture): if a sidecar already exists at the target,
    its scan identity must agree with the one being written — a regeneration whose
    ``source_scan.sha256`` or page count disagrees fails loud
    (:class:`~engine.errors.StaleArtifactError`), because boxes from a *different* scan silently
    replacing boxes an earlier run measured is exactly the drift the fingerprint exists to catch.
    An existing file that cannot even be parsed also refuses (do not trust the silent path); the
    sidecar is disposable, so the deliberate human escape is deleting the stale file.
    """
    path = geom_sidecar_path(workspace, sidecar.witness_id)
    if path.is_file():
        try:
            existing = read_json(path)
        except (json.JSONDecodeError, OSError, UnicodeDecodeError, RecursionError) as exc:
            raise StaleArtifactError(
                f"existing geometry sidecar at {path} is unreadable ({exc}) — refusing to clobber "
                f"it silently; delete the stale file to regenerate"
            ) from exc
        old_scan = existing.get("source_scan") if isinstance(existing, Mapping) else None
        if not isinstance(old_scan, Mapping):
            raise StaleArtifactError(
                f"existing geometry sidecar at {path} carries no source_scan fingerprint — "
                f"refusing to clobber it silently; delete the stale file to regenerate"
            )
        new = sidecar.source_scan
        if old_scan.get("sha256") != new.sha256 or old_scan.get("n_pages") != new.n_pages:
            raise StaleArtifactError(
                f"geometry-sidecar regeneration for witness {sidecar.witness_id!r} disagrees with "
                f"the existing sidecar's scan identity (existing sha256={old_scan.get('sha256')!r} "
                f"n_pages={old_scan.get('n_pages')!r}, new sha256={new.sha256!r} "
                f"n_pages={new.n_pages!r}) — the scan changed under the sidecar (G-19); delete the "
                f"stale sidecar only as a deliberate act"
            )
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_json(path, to_json(sidecar))
    return path


def load_geom_sidecar(workspace: BookWorkspace, witness_id: str) -> GeomSidecar:
    """Read + validate the sidecar for ``witness_id``, or fail loud (G-18): absent →
    :class:`~engine.errors.MissingInputError`; non-JSON / stale / malformed / id-mismatched →
    :class:`~engine.errors.StaleArtifactError`."""
    path = geom_sidecar_path(workspace, witness_id)
    if not path.is_file():
        raise MissingInputError(f"geometry sidecar for witness {witness_id!r} not found at {path}")
    try:
        data = read_json(path)
    except (json.JSONDecodeError, OSError, UnicodeDecodeError, RecursionError) as exc:
        # The full house wrap set (errors.py load-boundary contract): non-JSON, unreadable,
        # non-UTF-8, and parse-depth blowup are all present-but-unloadable — StaleArtifactError,
        # never a bare traceback (G-18's totality).
        raise StaleArtifactError(
            f"geometry sidecar for witness {witness_id!r} at {path} is unloadable: {exc}"
        ) from exc
    sidecar = from_json(data)
    if sidecar.witness_id != witness_id:
        raise StaleArtifactError(
            f"geometry-sidecar id mismatch: file for {witness_id!r} carries witness_id "
            f"{sidecar.witness_id!r}"
        )
    return sidecar


def with_detector_fields(
    sidecar: GeomSidecar, by_page: Mapping[int, Mapping[str, object]]
) -> GeomSidecar:
    """Populate the schema-v2 detector fields on matched pages (DT-12 — the S2.2 ``order_qa`` feed).

    ``by_page`` maps a scan page → ``{n_cols, n_cols_source, order_qa}`` (the resolved column
    decision + the QA cross-check). Only **matched** pages carry detector fields, so ``by_page``
    must key matched pages only — a page that is routed/declined/absent is an error (the caller
    computed a verdict for a page the sidecar cannot attach it to), never a silent skip. Returns a
    new sidecar; the input is untouched (frozen)."""
    if not by_page:
        return sidecar
    allowed = frozenset({"n_cols", "n_cols_source", "order_qa"})
    new_pages = dict(sidecar.pages)
    for page, fields in by_page.items():
        unknown = sorted(set(fields) - allowed)
        if unknown:
            # Reject a typo'd key rather than silently dropping it (partial data loss) — the same
            # posture as the loaders' _reject_unknown_keys.
            raise ValueError(
                f"with_detector_fields got unknown field key(s) {unknown} for page {page} — the "
                f"detector fields are exactly {sorted(allowed)}"
            )
        record = new_pages.get(page)
        if record is None or record.status != PAGE_MATCHED:
            status = record.status if record is not None else "absent"
            raise ValueError(
                f"cannot attach detector fields to page {page}: its record is {status!r}, not "
                f"{PAGE_MATCHED!r} — the S2.2 feed measures accepted geometry only"
            )
        new_pages[page] = replace(
            record,
            n_cols=fields.get("n_cols"),
            n_cols_source=fields.get("n_cols_source"),
            order_qa=fields.get("order_qa"),
        )
    return replace(sidecar, pages=new_pages)


def assert_source_scan_matches(sidecar: GeomSidecar, *, sha256: str, n_pages: int) -> None:
    """The replay-side fingerprint check (G-19, DT-12/R15): any seam re-invocation compares the
    recorded scan identity against the live scan and fails loud on mismatch
    (:class:`~engine.errors.StaleArtifactError`) — so a consumer either replays on
    provably-identical inputs or knows it did not."""
    recorded = sidecar.source_scan
    if recorded.sha256 != sha256 or recorded.n_pages != n_pages:
        raise StaleArtifactError(
            f"source scan drifted under the geometry sidecar for witness {sidecar.witness_id!r}: "
            f"recorded sha256={recorded.sha256!r} n_pages={recorded.n_pages}, live sha256={sha256!r} "
            f"n_pages={n_pages} — regenerate the sidecar or restore the recorded scan (G-19)"
        )


# --- P-5 auto-absent tripwire (G-26) ------------------------------------------------------------ #

#: Warn-tier token bands for the auto-absent table (reason × band): the ≤3-token furniture tail,
#: prose-sized atoms at the leg-B floor, and long prose.
_BANDS = (("<=3", 1, TRIPWIRE_PROSE_MIN_TOKENS - 1), ("4-10", TRIPWIRE_PROSE_MIN_TOKENS, 10), (">10", 11, None))


def _band_of(count: int) -> str:
    for name, lo, hi in _BANDS:
        if count >= lo and (hi is None or count <= hi):
            return name
    return _BANDS[0][0]  # count == 0 folds into the shortest band


def assert_auto_absent_tripwire(
    sidecar: GeomSidecar, token_counts: Mapping[str, int]
) -> dict:
    """The P-5 two-leg auto-absent tripwire (RULED 2026-07-03; G-26) — hard-fails on either leg,
    returns the warn-tier stats for the run report.

    Both legs are computed over **accepted pages only**: every record in ``sidecar.atoms`` sits on
    a matched page by model invariant, so the record set *is* the accepted-page population — a
    routed page's pending atoms never enter either numerator or denominator. ``token_counts`` maps
    atom id → DT-8-normalizer token count and must cover every record-bearing atom (a missing
    count is a caller error, ``ValueError`` — a silently shrunken denominator would loosen both
    legs).

    - **Leg A (token mass):** auto-absent token mass / accepted-page token mass >
      :data:`TRIPWIRE_ABSENT_MASS_MAX` → :class:`~engine.structure.geometry.GeometryError`.
    - **Leg B (scoped count):** among atoms with ≥ :data:`TRIPWIRE_PROSE_MIN_TOKENS` witness
      tokens, auto-absent rate > :data:`TRIPWIRE_PROSE_ABSENT_RATE_MAX` → same.

    A trip means the automation premise failed — fix the matcher; the bar is never raised to
    un-fire a trip (the pre-committed retune protocol, DT-8).
    """
    missing = [a for a in sidecar.atoms if a not in token_counts]
    if missing:
        raise ValueError(
            f"token_counts is missing {len(missing)} record-bearing atom(s) (first: {missing[:3]}) — "
            f"the tripwire denominators must cover every accepted-page atom"
        )

    total_mass = 0
    absent_mass = 0
    prose_total = 0
    prose_absent = 0
    bands: dict[str, dict] = {
        name: {"atoms": 0, "absent_atoms": 0, "token_mass": 0, "absent_token_mass": 0, "reasons": {}}
        for name, _, _ in _BANDS
    }
    confidences: list[float] = []
    for atom_id, record in sidecar.atoms.items():
        count = token_counts[atom_id]
        if not (_is_int(count) and count >= 0):
            raise ValueError(f"token_counts[{atom_id!r}] must be a non-negative integer, got {count!r}")
        band = bands[_band_of(count)]
        band["atoms"] += 1
        band["token_mass"] += count
        total_mass += count
        confidences.append(record.match_confidence)
        if count >= TRIPWIRE_PROSE_MIN_TOKENS:
            prose_total += 1
        if record.status == ATOM_UNMATCHED:
            absent_mass += count
            band["absent_atoms"] += 1
            band["absent_token_mass"] += count
            band["reasons"][record.reason] = band["reasons"].get(record.reason, 0) + 1
            if count >= TRIPWIRE_PROSE_MIN_TOKENS:
                prose_absent += 1

    absent_mass_rate = (absent_mass / total_mass) if total_mass else 0.0
    prose_absent_rate = (prose_absent / prose_total) if prose_total else 0.0

    if absent_mass_rate > TRIPWIRE_ABSENT_MASS_MAX:
        raise GeometryError(
            f"auto-absent tripwire leg A fired: {absent_mass_rate:.4f} of accepted-page token mass "
            f"is auto-absent (> {TRIPWIRE_ABSENT_MASS_MAX}) — real prose mass is absent; the "
            f"automation premise failed. Fix the matcher; never raise the bar to un-fire a trip "
            f"(P-5/G-26)"
        )
    if prose_absent_rate > TRIPWIRE_PROSE_ABSENT_RATE_MAX:
        raise GeometryError(
            f"auto-absent tripwire leg B fired: {prose_absent_rate:.4f} of "
            f">={TRIPWIRE_PROSE_MIN_TOKENS}-token atoms on accepted pages are auto-absent "
            f"(> {TRIPWIRE_PROSE_ABSENT_RATE_MAX}) — systematic absence, never honest residue; the "
            f"automation premise failed. Fix the matcher; never raise the bar to un-fire a trip "
            f"(P-5/G-26)"
        )

    histogram: dict[str, int] = {}
    for i in range(10):
        lo = i / 10
        hi = (i + 1) / 10
        key = f"{lo:.1f}-{hi:.1f}"
        histogram[key] = sum(1 for c in confidences if (lo <= c < hi) or (i == 9 and c == 1.0))
    flags = [
        f"band {name}: auto-absent token mass {band['absent_token_mass']}/{total_mass} exceeds "
        f"{TRIPWIRE_WARN_BAND_MASS:.0%} of accepted-page token mass"
        for name, band in bands.items()
        if total_mass and band["absent_token_mass"] / total_mass > TRIPWIRE_WARN_BAND_MASS
    ]
    return {
        "absent_token_mass_rate": absent_mass_rate,
        "prose_absent_rate": prose_absent_rate,
        "bands": bands,
        "confidence_histogram": histogram,
        "flags": flags,
    }
