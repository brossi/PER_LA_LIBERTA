# --- inv 23 for v2 (S5.1): the fingerprint fixture births the widened v2 shape -------------------- #

REBIND_POSITIVE = FIXTURES / "rebind_positive_structure_map.json"


class _MiniStore:
    """A minimal §4-header reader for the hand-authored v2 fingerprint fixture — its atom universe
    is three included body atoms (a0/a1/a2), not the differ book's real streams. The v2 birth gate
    proves the widened *shape* validates; the real-stream backing stays the differ fixture's job."""

    def __init__(self, included: tuple[str, ...]) -> None:
        self._included = tuple(included)
        self._scope = {a: structure.PROCESSING_SCOPE_INCLUDED for a in included}

    def included_atom_ids(self) -> tuple[str, ...]:
        return self._included

    def contains(self, atom_id: str) -> bool:
        return atom_id in self._scope

    def scope_of(self, atom_id: str) -> str | None:
        return self._scope.get(atom_id)


def test_v3_boundary_anchor_fixture_validates_and_v3_is_born():
    # The v3 birth gate: a NON-PLL conforming map that populates stored slot boundary anchors
    # validates through the born-agnostic loader. Two unconditional asserts (X10): a
    # broken fixture reds assert 1 even after the flip; a validating fixture with no flip reds
    # assert 2 (the pre-flip red-first state).
    smap = structure.load_structure_map(REBIND_POSITIVE, _MiniStore(("a0", "a1", "a2")))
    assert isinstance(smap, structure.StructureMap)
    assert STRUCTURE_MAP_SCHEMA_STATUS[STRUCTURE_MAP_SCHEMA_VERSION] == SCHEMA_STATUS_BORN


def test_v3_birth_fixture_actually_carries_the_boundary_anchor_shape():
    # Non-vacuity guard: v3 birth must exercise the newly stored start/end anchor pairs.
    doc = json.loads(REBIND_POSITIVE.read_text(encoding="utf-8"))
    fingerprints = [
        node["rebind_anchors"]["content_fingerprint"]
        for node in doc["nodes"]
        if "content_fingerprint" in node.get("rebind_anchors", {})
    ]
    assert fingerprints, "the v2 birth fixture must POPULATE content_fingerprint (the v2 novelty)"
    assert any("body" in fp for fp in fingerprints), "expected a per-slot body fingerprint"
    boundary_anchors = [
        node["rebind_anchors"]["boundary_anchors"]
        for node in doc["nodes"]
        if "boundary_anchors" in node.get("rebind_anchors", {})
    ]
    assert boundary_anchors
    assert all({"start", "end"} <= set(pair["body"]) for pair in boundary_anchors)


# --- the manifest is live-bound: hand-authored values == what the producers stamp ------------------ #


def test_differ_manifest_matches_the_live_producers_over_the_committed_sources():
    # The hand-authored map's manifest (stream hashes, split canonical hashes, layers, renderer
    # version) must equal build_manifest's output over the captured streams — hand-authorship with
    # a live verification, NOT generation (inv 23: the fixture is never produced by the path it
    # validates). A drift in either direction — a source edit without a manifest refresh, or a
    # producer change (hash field list, layer stamping) without a fixture refresh — reds here.
    doc = json.loads(DIFFER.read_text(encoding="utf-8"))
    fragment = doc["manifest"]["resource_lineage"]
    lineage = ResourceLineage(
        resource_version=fragment["resource"]["version"],
        resource_descriptor=_canonical(fragment["resource"]["descriptor"]),
        resource_stale_class=fragment["resource"]["stale_class"],
        normalizer_version=fragment["normalizer"]["version"],
        normalizer_descriptor=_canonical(fragment["normalizer"]["descriptor"]),
        normalizer_stale_class=fragment["normalizer"]["stale_class"],
    )
    live = structure.build_manifest(
        streams=_differ_streams(),
        canonical_stream_id="canonical",
        resource_lineage=lineage,
        profile_version=doc["manifest"]["profile_version"],
        recognizer_version=doc["manifest"]["recognizer_version"],
    )
    assert doc["manifest"] == live


def test_differ_furniture_is_real_witness_furniture():
    # The furniture entries resolve to genuinely EXCLUDED atoms in the captured witness stream —
    # the §3.B.1 witness-id namespace exercised against real capture output, with furniture roles
    # (running-head, catchword) PLL's page-number profile never mints.
    streams = _differ_streams()
    doc = json.loads(DIFFER.read_text(encoding="utf-8"))
    excluded = {
        a.atom_id: a.capture_provenance_class
        for a in streams["wdiffer-a"].atoms
        if a.processing_scope == structure.PROCESSING_SCOPE_EXCLUDED
    }
    declared = {f["atom_id"]: f["capture_role"] for f in doc["furniture_atoms"]}
    assert declared == excluded  # same atoms, same roles — capture and map agree exactly


