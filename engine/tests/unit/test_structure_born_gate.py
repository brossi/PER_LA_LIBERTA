FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "structure"
DIFFER = FIXTURES / "differ_structure_map.json"
WITNESS_A = FIXTURES / "differ_witness_a.txt"
WITNESS_B = FIXTURES / "differ_witness_b.txt"


def _classify_differ_furniture(line: str) -> str | None:
    """The differ book's furniture grammar (fixture-local, like every per-book classifier): the
    running head and the ``·``-decorated catchword line; everything else is body."""
    if line.strip() == "THE DIFFER CODEX":
        return "running-head"
    if line.strip().startswith("·"):
        return "catchword"
    return None


def _differ_streams() -> dict[str, structure.AtomStream]:
    """The differ book's atom store, built through the REAL producers from the committed sources."""
    src_a = WITNESS_A.read_text(encoding="utf-8")
    src_b = WITNESS_B.read_text(encoding="utf-8")
    atoms_a = structure.capture_witness(src_a, "wdiffer-a", classify_line=_classify_differ_furniture)
    atoms_b = structure.capture_witness(src_b, "wdiffer-b")
    canonical = structure.build_canonical(
        {"wdiffer-a": atoms_a, "wdiffer-b": atoms_b}, ("wdiffer-a", "wdiffer-b")
    )
    return {
        "wdiffer-a": structure.AtomStream.witness(
            "wdiffer-a", atoms_a, structure.gap_records(atoms_a, src_a), src_a
        ),
        "wdiffer-b": structure.AtomStream.witness(
            "wdiffer-b", atoms_b, structure.gap_records(atoms_b, src_b), src_b
        ),
        "canonical": structure.AtomStream.canonical(canonical),
    }


def _reader() -> structure.StreamAtomReader:
    return structure.StreamAtomReader(_differ_streams())


def _load():
    return structure.load_structure_map(DIFFER, _reader())


